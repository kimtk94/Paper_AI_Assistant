"""Follow SKKU-seeded researchers across later PubMed publications.

High-confidence mode follows authors by ORCID using PubMed Author Identifier [auid].
Optional name fallback is available for authors without ORCID, but it is lower confidence.

Input:
  papers.json generated by src/skku_pubmed_lineage.py

Outputs:
  author_registry.csv
  lineage_papers.csv / lineage_papers.json
  continuation_edges.csv / continuation_edges.json
  lineage_edges.csv / lineage_edges.json
  paper_annotations.csv / paper_annotations.json
  researcher_summary.csv / researcher_summary.json
  research_trajectory.html
  continuation.md
"""

