def write_csv(path: Path, rows: list[dict]) -> None:
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    with path.open("w", newline="", encoding="utf-8-sig") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def write_report(
    path: Path,
    registry: list[TrackedAuthor],
    followed: list[FollowedPaper],
    edges: list[ContinuationEdge],
    lineage_edges: list[ResearchLineageEdge],
) -> None:
    author_counts = Counter()
    by_key: dict[str, list[FollowedPaper]] = defaultdict(list)
    for paper in followed:
        for key, name in zip(paper.tracked_author_keys, paper.tracked_authors):
            author_counts[name] += 1
            by_key[key].append(paper)

    rel_counts = Counter(e.relation for e in edges)
    lineage_counts = Counter(e.relation for e in lineage_edges)
    lines = [
        "# SKKU-seeded PubMed Author Continuation",
        "",
        f"- Generated UTC: {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        f"- Tracked researchers: {len(registry)}",
        f"- Unique followed publications: {len(followed)}",
        f"- Author-continuation edges: {rel_counts['author_continuation']}",
        f"- Direct citation edges: {rel_counts['citation']}",
        f"- Strong direct-citation continuations: {lineage_counts['direct_citation_continuation']}",
        f"- Direct citations within same researcher: {lineage_counts['direct_citation_same_author']}",
        f"- Author-only continuations: {lineage_counts['author_continuation_only']}",
        "",
        "## Lineage interpretation",
        "",
        "- Score 1.00: same tracked researcher and the later consecutive paper directly cites the earlier paper.",
        "- Score 0.95: same tracked researcher with a direct citation, but the papers are not consecutive in the publication timeline.",
        "- Score 0.85: direct citation between papers belonging to different tracked researchers.",
        "- Score 0.75: exact ORCID researcher continuation without a direct citation between consecutive papers.",
        "- Score 0.45: name-only researcher continuation without direct citation evidence.",
        "",
        "## Identity policy",
        "",
        "- High confidence: exact ORCID match through PubMed Author Identifier.",
        "- Low confidence: exact full-author-name fallback; manual review is recommended.",
        "- SKKU status here is seeded from publication-time affiliation, not proof of graduation/alumni status.",
        "",
        "## Researchers",
        "",
        "| Researcher | Confidence | ORCID | Followed papers |",
        "|---|---|---|---:|",
    ]
    for tracked in registry:
        lines.append(
            f"| {tracked.name} | {tracked.confidence} | {tracked.orcid or '-'} | "
            f"{len(by_key.get(tracked.key, []))} |"
        )

    lines += ["", "## Publication chains", ""]
    for tracked in registry:
        chain = sorted(
            by_key.get(tracked.key, []),
            key=lambda p: (p.year or 9999, p.pmid),
        )
        if not chain:
            continue
        lines.append(f"### {tracked.name}")
        lines.append(
            f"Confidence: **{tracked.confidence}**"
            + (f" · ORCID: {tracked.orcid}" if tracked.orcid else "")
        )
        for paper in chain:
            aff = "SKKU" if paper.skku_current else "non-SKKU / other affiliation"
            methods = ", ".join(paper.methods[:3]) or "method not classified"
            data_types = ", ".join(paper.data_types[:3]) or "data not classified"
            domain = paper.primary_domain or "domain not classified"
            topics = ", ".join(paper.topic_terms[:2]) or "topic not classified"
            disease = ", ".join(paper.disease_terms[:2]) or "phenotype not classified"
            lines.append(
                f"- {paper.year or 'Unknown'} · PMID {paper.pmid} · "
                f"[{paper.title}]({paper.pubmed_url}) · {aff} · "
                f"domain={domain} · topics={topics} · stage={paper.research_stage} · "
                f"disease={disease} · method={methods} · data={data_types}"
            )
            lines.append(f"  - Question: {paper.research_question}")
        lines.append("")

    strong = [
        edge for edge in lineage_edges
        if edge.relation in {"direct_citation_continuation", "direct_citation_same_author"}
    ]
    if strong:
        lines += ["", "## Strong research progression", ""]
        for edge in strong[:50]:
            names = ", ".join(edge.tracked_authors) or "tracked researcher"
            lines.append(
                f"- PMID {edge.source} → {edge.target} · {names} · "
                f"score={edge.score:.2f} · {edge.progression or 'continuation'}"
            )

    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Follow SKKU-seeded authors across later PubMed publications."
    )
    parser.add_argument("--seed-json", default="outputs/skku_pubmed_lineage/papers.json")
    parser.add_argument("--email", default=os.getenv("NCBI_EMAIL", ""))
    parser.add_argument("--api-key", default=os.getenv("NCBI_API_KEY", ""))
    parser.add_argument("--start-year", type=int, default=2002)
    parser.add_argument("--end-year", type=int, default=datetime.now().year)
    parser.add_argument("--max-authors", type=int, default=100)
    parser.add_argument("--max-per-author", type=int, default=200)
    parser.add_argument("--allow-name-fallback", action="store_true")
    parser.add_argument("--with-citations", action="store_true")
    parser.add_argument("--max-citation-checks", type=int, default=300)
    parser.add_argument("--output-dir", default="outputs/skku_pubmed_followup")
    args = parser.parse_args()

    if not args.email:
        parser.error("Provide --email or set NCBI_EMAIL.")

    seed_records = load_seed(Path(args.seed_json))
    registry = build_registry(seed_records, args.allow_name_fallback)
    registry = registry[: args.max_authors]
    print(
        f"[registry] researchers={len(registry)} "
        f"(ORCID-first; ranked by SKKU seed-paper count; "
        f"name fallback={args.allow_name_fallback})",
        file=sys.stderr,
    )

    client = PubMedClient(args.email, args.api_key)
    papers, paper_authors, registry_map = collect_followups(
        client=client,
        registry=registry,
        start_year=args.start_year,
        end_year=args.end_year,
        max_per_author=args.max_per_author,
    )

    annotations = {
        pmid: annotate_paper(paper)
        for pmid, paper in papers.items()
    }

    followed = [
        make_followed_paper(papers[pmid], keys, registry_map, annotations[pmid])
        for pmid, keys in paper_authors.items()
    ]
    followed.sort(key=lambda p: (p.year, p.pmid), reverse=True)

    edges = make_continuation_edges(papers, paper_authors, registry_map)
    citation_stats: dict = {
        "citation_check_strategy": "disabled",
        "citation_checks": 0,
        "citation_checkable_papers": len(papers),
        "citation_coverage_fraction": 0.0,
    }
    if args.with_citations:
        edges = add_direct_citation_edges(
            client,
            papers,
            paper_authors,
            edges,
            args.max_citation_checks,
            stats=citation_stats,
        )

    lineage_edges = build_research_lineage_edges(
        edges,
        paper_authors,
        registry_map,
        annotations,
    )
    trajectories = build_researcher_trajectories(
        registry,
        followed,
        lineage_edges,
    )

    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)

    registry_rows = []
    for item in registry:
        row = asdict(item)
        row["seed_pmids"] = "; ".join(item.seed_pmids)
        registry_rows.append(row)
    write_csv(out / "author_registry.csv", registry_rows)

    followed_rows = []
    for item in followed:
        row = asdict(item)
        row["tracked_authors"] = "; ".join(item.tracked_authors)
        row["tracked_author_keys"] = "; ".join(item.tracked_author_keys)
        row["current_affiliations"] = " | ".join(item.current_affiliations)
        row["research_domains"] = "; ".join(item.research_domains)
        row["topic_terms"] = "; ".join(item.topic_terms)
        row["disease_terms"] = "; ".join(item.disease_terms)
        row["methods"] = "; ".join(item.methods)
        row["data_types"] = "; ".join(item.data_types)
        followed_rows.append(row)
    write_csv(out / "lineage_papers.csv", followed_rows)

    annotation_rows = []
    for item in annotations.values():
        row = asdict(item)
        row["research_domains"] = "; ".join(item.research_domains)
        row["topic_terms"] = "; ".join(item.topic_terms)
        row["disease_terms"] = "; ".join(item.disease_terms)
        row["methods"] = "; ".join(item.methods)
        row["data_types"] = "; ".join(item.data_types)
        row["evidence_terms"] = "; ".join(item.evidence_terms)
        annotation_rows.append(row)
    write_csv(out / "paper_annotations.csv", annotation_rows)

    trajectory_rows = []
    for item in trajectories:
        row = asdict(item)
        row["top_domains"] = "; ".join(item.top_domains)
        row["top_topics"] = "; ".join(item.top_topics)
        row["top_diseases"] = "; ".join(item.top_diseases)
        row["top_methods"] = "; ".join(item.top_methods)
        row["top_data_types"] = "; ".join(item.top_data_types)
        row["stage_path"] = " -> ".join(item.stage_path)
        trajectory_rows.append(row)
    write_csv(out / "researcher_summary.csv", trajectory_rows)

    write_csv(out / "continuation_edges.csv", [asdict(e) for e in edges])

    lineage_rows = []
    for item in lineage_edges:
        row = asdict(item)
        row["tracked_authors"] = "; ".join(item.tracked_authors)
        lineage_rows.append(row)
    write_csv(out / "lineage_edges.csv", lineage_rows)

    (out / "lineage_papers.json").write_text(
        json.dumps([asdict(x) for x in followed], ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    (out / "paper_annotations.json").write_text(
        json.dumps([asdict(x) for x in annotations.values()], ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    (out / "continuation_edges.json").write_text(
        json.dumps([asdict(x) for x in edges], ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    (out / "lineage_edges.json").write_text(
        json.dumps([asdict(x) for x in lineage_edges], ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    (out / "researcher_summary.json").write_text(
        json.dumps([asdict(x) for x in trajectories], ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    render_research_trajectory_html(
        out / "research_trajectory.html",
        followed,
        lineage_edges,
        trajectories,
    )
    write_report(out / "continuation.md", registry, followed, edges, lineage_edges)

    summary = {
        "followup_version": 4,
        "registry_policy": "conservative_affiliation_then_seed_paper_count_ranking",
        "start_year": args.start_year,
        "end_year": args.end_year,
        "max_authors": args.max_authors,
        "max_per_author": args.max_per_author,
        "max_citation_checks": args.max_citation_checks,
        **citation_stats,
        "tracked_researchers": len(registry),
        "high_confidence_orcid": sum(x.confidence == "high" for x in registry),
        "low_confidence_name": sum(x.confidence == "low" for x in registry),
        "unique_followed_papers": len(followed),
        "edges": len(edges),
        "edge_types": dict(Counter(e.relation for e in edges)),
        "lineage_edges": len(lineage_edges),
        "lineage_types": dict(Counter(e.relation for e in lineage_edges)),
        "strong_direct_lineage": sum(
            e.relation in {"direct_citation_continuation", "direct_citation_same_author"}
            for e in lineage_edges
        ),
        "annotated_papers": len(annotations),
        "papers_with_methods": sum(bool(a.methods) for a in annotations.values()),
        "papers_with_data_types": sum(bool(a.data_types) for a in annotations.values()),
        "papers_with_disease_terms": sum(bool(a.disease_terms) for a in annotations.values()),
        "primary_domain_counts": dict(Counter(a.primary_domain for a in annotations.values())),
        "research_stages": dict(Counter(a.research_stage for a in annotations.values())),
        "researcher_trajectories": len(trajectories),
        "researchers_with_strong_lineage": sum(
            t.strong_lineage_count > 0 for t in trajectories
        ),
    }
    (out / "summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return 0


